<?php

namespace App\Console\Commands;

use App\Console\Commands\Concerns\ProcessesPhotos;
use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;
use Illuminate\Support\Collection;
use Illuminate\Support\Facades\File;

/**
 * Builds the photo credits from the per-photo manifests written by the import commands:
 * docs/image-credits.md (repository documentation) and a JSON file read by the SPA's
 * /credits page. Both files are generated: edit the sources, never the output.
 */
#[Signature('tomobilti:image-credits
    {--cars-path= : Car photos folder (default: database/seeders/assets/cars)}
    {--site-path= : Site photos folder (default: ../frontend/src/assets/photos)}
    {--markdown= : Markdown output (default: ../docs/image-credits.md)}
    {--json= : JSON output for the SPA (default: ../frontend/src/data/image-credits.json)}')]
#[Description('Generate docs/image-credits.md and the frontend credits JSON from the photo manifests')]
class GenerateImageCredits extends Command
{
    use ProcessesPhotos;

    /**
     * Execute the console command.
     */
    public function handle(): int
    {
        $cars = $this->manifests($this->option('cars-path') ?: database_path('seeders/assets/cars'), recursive: true)
            ->sortBy(fn (array $photo): string => "{$photo['model']}|{$photo['car']}|{$photo['file']}")
            ->values();
        $site = $this->manifests($this->option('site-path') ?: base_path('../frontend/src/assets/photos'), recursive: false)
            ->sortBy('file')
            ->values();

        $markdownPath = $this->option('markdown') ?: base_path('../docs/image-credits.md');
        $jsonPath = $this->option('json') ?: base_path('../frontend/src/data/image-credits.json');

        File::ensureDirectoryExists(dirname($markdownPath));
        File::put($markdownPath, $this->markdown($site, $cars));

        File::ensureDirectoryExists(dirname($jsonPath));
        $this->writeJson($jsonPath, [
            'site' => $site->map(fn (array $photo): array => $this->credit($photo) + [
                'description' => $photo['description'],
            ])->all(),
            'cars' => $cars->map(fn (array $photo): array => $this->credit($photo) + [
                'model' => $photo['model'],
                'car' => $photo['car'],
                'view' => $photo['view'],
                'note' => $photo['note'] ?? null,
            ])->all(),
        ]);

        $this->components->info("Crédits générés : {$site->count()} photos du site, {$cars->count()} photos de voitures.");

        return self::SUCCESS;
    }

    /**
     * Every per-photo manifest in a folder (sources.json is the input, not a manifest).
     *
     * @return Collection<int, array<string, mixed>>
     */
    private function manifests(string $path, bool $recursive): Collection
    {
        if (! File::isDirectory($path)) {
            return collect();
        }

        $files = $recursive ? File::allFiles($path) : File::files($path);

        return collect($files)
            ->filter(fn ($file): bool => $file->getExtension() === 'json' && $file->getFilename() !== 'sources.json')
            ->map(fn ($file): array => $this->readJson($file->getPathname()))
            ->values();
    }

    /**
     * Fields shared by every credit entry.
     *
     * @param  array<string, mixed>  $photo
     * @return array<string, mixed>
     */
    private function credit(array $photo): array
    {
        return [
            'file' => $photo['file'],
            'title' => $photo['title'] ?? '',
            'author' => $photo['author'],
            'author_url' => $photo['author_url'] ?? null,
            'license' => $photo['license'],
            'license_url' => $photo['license_url'],
            'source' => $photo['source'],
            'source_url' => $photo['source_url'],
            'changes' => $photo['changes'],
            'derivative_license' => $photo['derivative_license'] ?? $this->derivativeLicense($photo['license']),
        ];
    }

    /**
     * @param  Collection<int, array<string, mixed>>  $site
     * @param  Collection<int, array<string, mixed>>  $cars
     */
    private function markdown(Collection $site, Collection $cars): string
    {
        $lines = [
            '# Image credits',
            '',
            'Generated by `php artisan tomobilti:image-credits` from the per-photo manifests. Do not edit this file by hand: edit the `sources.json` files and run the import commands again.',
            '',
            'CC BY and CC BY-SA ask to indicate changes: the "Changes" column lists them for every photo (all were cropped, resized and converted to WebP; some also have a blurred license plate). The modified versions of CC BY-SA photos are shared under the same license as the original (CC BY-SA, same version). The SPA lists the same credits on its `/credits` page.',
            '',
            "## Site photos ({$site->count()})",
            '',
            'Files in `frontend/src/assets/photos/`.',
            '',
            '| Photo | File | Author | License | Changes | Source |',
            '| --- | --- | --- | --- | --- | --- |',
            ...$site->map(fn (array $photo): string => $this->row([
                $photo['description'],
                "`{$photo['file']}`",
                $this->link($photo['author'], $photo['author_url'] ?? null),
                $this->link($photo['license'], $photo['license_url']),
                $this->changes($photo),
                $this->link($photo['source'], $photo['source_url']),
            ])),
            '',
            "## Car photos ({$cars->count()})",
            '',
            'Files in `backend/database/seeders/assets/cars/{car-slug}/`, copied to the public disk by the `CarSeeder`.',
            '',
            '| Model | File | Author | License | Changes | Source |',
            '| --- | --- | --- | --- | --- | --- |',
            ...$cars->map(fn (array $photo): string => $this->row([
                $photo['model'].(! empty($photo['note']) ? " ({$photo['note']})" : ''),
                "`{$photo['car']}/{$photo['file']}`",
                $this->link($photo['author'], $photo['author_url'] ?? null),
                $this->link($photo['license'], $photo['license_url']),
                $this->changes($photo),
                $this->link($photo['source'], $photo['source_url']),
            ])),
            '',
        ];

        return implode("\n", $lines);
    }

    /**
     * @param  list<string>  $cells
     */
    private function row(array $cells): string
    {
        return '| '.implode(' | ', array_map(fn (string $cell): string => str_replace('|', '\|', $cell), $cells)).' |';
    }

    /**
     * The changes made to the photo, plus the license of the modified version when the
     * original is ShareAlike.
     *
     * @param  array<string, mixed>  $photo
     */
    private function changes(array $photo): string
    {
        $derivativeLicense = $photo['derivative_license'] ?? $this->derivativeLicense($photo['license']);

        return $derivativeLicense
            ? "{$photo['changes']}. Version modifiée partagée sous la même licence ({$derivativeLicense})"
            : $photo['changes'];
    }

    private function link(string $text, ?string $url): string
    {
        return $url ? "[{$text}]({$url})" : $text;
    }
}
