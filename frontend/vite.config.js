import tailwindcss from '@tailwindcss/vite'
import react from '@vitejs/plugin-react'
import { defineConfig, loadEnv } from 'vite'
import contentSecurityPolicy from './build/contentSecurityPolicy.js'
import preloads from './build/preloads.js'
import seoFiles from './build/seoFiles.js'

// https://vite.dev/config/
export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, process.cwd())
  // Public URL of the SPA (canonical URLs, link previews, robots.txt). index.html reads
  // %VITE_SITE_URL% and %VITE_API_URL%, so both always have a value.
  process.env.VITE_SITE_URL = (env.VITE_SITE_URL || 'http://localhost:5173').replace(/\/$/, '')
  process.env.VITE_API_URL = env.VITE_API_URL || 'http://localhost:8000'

  return {
    plugins: [react(), tailwindcss(), preloads(), seoFiles(process.env.VITE_SITE_URL)],
    server: {
      // Always "localhost" (never 127.0.0.1) so Sanctum cookies are shared with the API.
      host: 'localhost',
      port: 5173,
      strictPort: true,
      // The sitemap is generated by the API (production routes it the same way).
      proxy: { '/sitemap.xml': process.env.VITE_API_URL },
    },
    build: {
      // Fonts stay files (never data: URIs), so the CSP's font-src can stay 'self'.
      assetsInlineLimit: (file) => (file.endsWith('.woff2') ? false : undefined),
      rolldownOptions: {
        output: {
          /*
           * Vendor chunks, cached across deploys: each changes only when its library is
           * upgraded. Recharts (and d3, redux…) has no group: it stays in the lazy admin
           * dashboard chunk, so visitors and clients never download it.
           */
          codeSplitting: {
            groups: [
              { name: 'react', test: /node_modules[\\/](react|react-dom|scheduler)[\\/]/ },
              { name: 'router', test: /node_modules[\\/]react-router[\\/]/ },
              {
                name: 'motion',
                test: /node_modules[\\/](motion|motion-dom|motion-utils|framer-motion)[\\/]/,
              },
              {
                name: 'headlessui',
                test: /node_modules[\\/](@headlessui|@floating-ui|@react-aria|react-aria|@tanstack[\\/]react-virtual|@swc[\\/]helpers)[\\/]/,
              },
              {
                name: 'query',
                test: /node_modules[\\/]@tanstack[\\/](query-core|react-query)[\\/]/,
              },
              {
                // The calendar: only loaded when a date picker opens or the booking page shows.
                name: 'calendar',
                // Leave its dependencies (date-fns, cn, formatters) in the shared chunks:
                // pulled in here, they would make every page import this chunk.
                includeDependenciesRecursively: false,
                test: /node_modules[\\/](react-day-picker|@date-fns[\\/]tz|date-fns[\\/]locale[\\/]fr)[\\/.]|DateRangeCalendar\.jsx/,
              },
            ],
          },
        },
      },
    },
    preview: {
      host: 'localhost',
      port: 4173,
      strictPort: true,
      // The production headers of the SPA (docs/security.md), so the build is tested with them.
      headers: {
        'Content-Security-Policy': contentSecurityPolicy(process.env.VITE_API_URL),
        'X-Content-Type-Options': 'nosniff',
        'Referrer-Policy': 'strict-origin-when-cross-origin',
        'Permissions-Policy': 'camera=(), microphone=(), geolocation=(), payment=(), usb=()',
      },
    },
    // https://vitest.dev/config/
    test: {
      environment: 'jsdom',
      // Unit and component tests only: e2e/ belongs to Playwright Test (npm run test:e2e).
      include: ['src/**/*.test.{js,jsx}'],
      setupFiles: ['./src/test/setup.js'],
      css: false,
      restoreMocks: true,
    },
  }
})
